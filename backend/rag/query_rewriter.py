def enrich_query(query: str, max_expansions: int = 6) -> str:
    """
    用标准化术语扩展用户原始 query。

    Args:
        query: 用户原始问题
        max_expansions: 最多追加的扩展词数量（控制向量稀释程度）

    Returns:
        扩展后的 query 字符串。如果 query 中未命中任何映射词，返回原 query。

    设计原则:
        - 原 query 不修改（保留语义检索能力）
        - 扩展词追加在末尾（用空格分隔）
        - 去重（同一扩展词不重复追加）
        - 按 key 长度降序匹配（更具体的关键词优先，如「怎么退税」优先于「退税」）
    """
    seen_expansions: set[str] = set()
    expansions: list[str] = []

    # 按 key 长度降序排列，让更具体的关键词优先匹配
    sorted_keys = sorted(TERM_MAP.keys(), key=len, reverse=True)

    for colloquial in sorted_keys:
        standard_terms = TERM_MAP[colloquial]
        if colloquial in query:
            for term in standard_terms:
                if term not in seen_expansions and term not in query:
                    seen_expansions.add(term)
                    expansions.append(term)
                    if len(expansions) >= max_expansions:
                        break
        if len(expansions) >= max_expansions:
            break

    if not expansions:
        return query

    return query + " " + " ".join(expansions)


